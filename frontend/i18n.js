let CURRENT_LANG = localStorage.getItem("etijahak_lang") || "ar";

function t(key) {
  return (I18N[CURRENT_LANG] && I18N[CURRENT_LANG][key]) || I18N.ar[key] || key;
}

function applyTranslations() {
  document.documentElement.lang = CURRENT_LANG;
  document.documentElement.dir = CURRENT_LANG === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("lang-en", CURRENT_LANG === "en");

  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll(".lang-toggle").forEach(btn => {
    btn.textContent = CURRENT_LANG === "ar" ? "English" : "العربية";
  });
}

function setLanguage(lang) {
  CURRENT_LANG = lang;
  localStorage.setItem("etijahak_lang", lang);
  applyTranslations();
  // إعادة رسم أي محتوى ديناميكي معروض حاليًا (لو الدالة موجودة بالصفحة)
  if (typeof window.rerenderDynamicContent === "function") {
    window.rerenderDynamicContent();
  }
}

document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
  document.querySelectorAll(".lang-toggle").forEach(btn => {
    btn.addEventListener("click", () => {
      setLanguage(CURRENT_LANG === "ar" ? "en" : "ar");
    });
  });
});
